#!/usr/bin/env python3
"""
The Lain OS app icon from the brand's maskable icon (resources/lain-source.png,
the same file chat.lain-os.com uses): the face and halo without the "LAIN OS"
wordmark, which no launcher can render legibly at 48 dp.

Writes the adaptive icon (background colour, foreground and Android 13+
monochrome layers per density), legacy square and round icons, and the
512 px store icon. Run: python3 scripts/icon.py  (needs Pillow)
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageOps

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / 'android/app/src/main/res'
SOURCE = Image.open(ROOT / 'resources/lain-source.png').convert('RGBA')
BG = SOURCE.getpixel((6, 6))[:3]
# Face and halo; the wordmark starts at y≈385.
ART = SOURCE.crop((56, 8, 456, 372))


def canvas(size, scale):
    """The art centred on a square of the background colour, filling `scale` of it."""
    out = Image.new('RGBA', (size, size), BG + (255,))
    w = int(size * scale)
    h = int(w * ART.height / ART.width)
    art = ART.resize((w, h), Image.LANCZOS)
    out.paste(art, ((size - w) // 2, (size - h) // 2 + int(size * 0.02)), art)
    return out


def monochrome(size, scale):
    """White where the line art glows, transparent elsewhere: the system tints it."""
    full = canvas(size, scale)
    r, g, b, _ = full.split()
    glow = ImageOps.autocontrast(b.point(lambda v: max(0, v - 40) * 2))
    white = Image.new('RGBA', (size, size), (255, 255, 255, 0))
    white.putalpha(glow)
    return white


def masked(img, shape):
    mask = Image.new('L', img.size, 0)
    d = ImageDraw.Draw(mask)
    if shape == 'circle':
        d.ellipse((0, 0, img.size[0] - 1, img.size[1] - 1), fill=255)
    else:
        d.rounded_rectangle((0, 0, img.size[0] - 1, img.size[1] - 1), radius=int(img.size[0] * 0.22), fill=255)
    out = img.copy()
    out.putalpha(mask)
    return out


DENSITIES = {'ldpi': 0.75, 'mdpi': 1, 'hdpi': 1.5, 'xhdpi': 2, 'xxhdpi': 3, 'xxxhdpi': 4}
for name, k in DENSITIES.items():
    folder = RES / f'mipmap-{name}'
    folder.mkdir(parents=True, exist_ok=True)
    # Adaptive layers are 108 dp; the face fits the 66 dp safe circle.
    canvas(int(108 * k), 0.78).save(folder / 'ic_launcher_foreground.png')
    monochrome(int(108 * k), 0.78).save(folder / 'ic_launcher_monochrome.png')
    legacy = canvas(int(48 * k), 1.0)
    masked(legacy, 'rounded').save(folder / 'ic_launcher.png')
    masked(legacy, 'circle').save(folder / 'ic_launcher_round.png')

(RES / 'values/ic_launcher_background.xml').write_text(
    '<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
    f'    <color name="ic_launcher_background">#{BG[0]:02X}{BG[1]:02X}{BG[2]:02X}</color>\n</resources>\n')
adaptive = '''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/icon.py. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
    <monochrome android:drawable="@mipmap/ic_launcher_monochrome" />
</adaptive-icon>
'''
for f in ('ic_launcher.xml', 'ic_launcher_round.xml'):
    (RES / 'mipmap-anydpi-v26' / f).write_text(adaptive)
for stale in (RES / 'drawable/ic_launcher_background.xml', RES / 'drawable-v24/ic_launcher_foreground.xml', RES / 'drawable/ic_launcher_monochrome.xml'):
    stale.unlink(missing_ok=True)

canvas(1024, 0.86).save(ROOT / 'resources/icon.png')
store = ROOT / 'fastlane/metadata/android/en-US/images'
store.mkdir(parents=True, exist_ok=True)
canvas(512, 0.86).convert('RGB').save(store / 'icon.png')
print('icons written; background', BG)
